from openmm import XmlSerializer, app
from openmmtools import cache, alchemy, mcmc, multistate, states

from omm_readinputs import *
from omm_nonbonded import *
from omm_barostat import *
from omm_fep import *


parser = argparse.ArgumentParser()
parser.add_argument('-i', dest='inpfile', required=True, help='Input parameter file')
parser.add_argument('-f', dest='sysfile', required=True, help='Input OpenMM System XML file')
parser.add_argument('-c', dest='pdbfile', required=True, help='Input PDB file')
parser.add_argument('-o', dest='outfile', default='output', help='Output prefix')
args = parser.parse_args()

inputs = read_inputs(args.inpfile)

# ========== 1. Load System and Positions ==========
print("Loading alchemical system and coordinates...")
pdb = PDB(args.pdbfile)
ligand_info = get_ligand_info(pdb.topology)

alchemical_system = XmlSerializer.deserialize(open(args.sysfile, 'r').read())
updateNonbonded(alchemical_system, ligand_info, inputs)
updateBarostat(alchemical_system, inputs)

positions = minimize(alchemical_system, pdb, inputs.nstep_mini)


# ========== 2. Select Ligand Atoms ==========
ligand_atoms = [atom.index for atom in pdb.topology.atoms() if getattr(atom, 'weight', 0.0) > 0.0]
print(f"Found {len(ligand_atoms)} ligand atoms for alchemical region.")


# ========== 3. Set up Lambda Protocol ==========
lambda_schedule = get_lambda_schedule(inputs.fep_lambdas, inputs.fep_num_lambdas)
lambda_functions = get_lambda_functions(inputs.fep_lambda_func)

thermodynamic_states = []
sampler_states = []
for lam in lambda_schedule:
    # Alchemical lambda state
    alchemical_state = RelativeAlchemicalState.from_system(alchemical_system)
    for parameter_name in lambda_functions:
        lambda_value = lambda_functions[parameter_name](lam)
        setattr(alchemical_state, parameter_name, lambda_value)

    # Thermodynamic state at constant temperature
    thermodynamic_state = states.ThermodynamicState(system=alchemical_system,
                                                    temperature=inputs.temperature)

    # Combine both into a CompoundThermodynamicState
    compound_state = states.CompoundThermodynamicState(thermodynamic_state,
                                                       composable_states=[alchemical_state])
    thermodynamic_states.append(compound_state)

    # Same positions for all replicas
    box = alchemical_system.getDefaultPeriodicBoxVectors()
    sampler_state = states.SamplerState(positions=positions, box_vectors=box)
    sampler_states.append(sampler_state)

print(f"Created {len(thermodynamic_states)} lambda windows.")


# ========== 4. Define Sampler Move ==========
move = mcmc.LangevinDynamicsMove(
    timestep=inputs.dt,
    collision_rate=inputs.fep_collision_rate,
    n_steps=inputs.nstep,
    reassign_velocities=inputs.fep_reassign_velocities,
    n_restart_attempts=inputs.fep_num_restart_attempts,
    constraint_tolerance=inputs.fep_constraint_tolerance
)


# ========== 5. Set up Replica Exchange Simulation ==========
simulation = multistate.ReplicaExchangeSampler(mcmc_moves=move)
chkfile = os.path.basename(args.outfile) + ".chk"
reporter = multistate.MultiStateReporter(storage=f"{args.outfile}.nc",
                                         analysis_particle_indices=ligand_atoms,
                                         checkpoint_interval=inputs.niter_chk,
                                         checkpoint_storage=chkfile,
                                         position_interval=inputs.niter_pos,
                                         velocity_interval=inputs.niter_vel)
simulation.create(thermodynamic_states, sampler_states, reporter)


# ========== 6. Run Simulation ==========
print("Running replica exchange alchemical free energy simulation...")
print("Running minimization...")
simulation.minimize(max_iterations=inputs.nstep_mini) # MINIMIZATION
print("Running equilibration...")
simulation.equilibrate(int(inputs.nstep_equi/inputs.nstep)) # EQUILIBRATION
