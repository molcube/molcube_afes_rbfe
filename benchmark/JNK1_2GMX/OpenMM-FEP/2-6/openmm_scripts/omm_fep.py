def get_ligand_info(topology):
    ligand_info = {'core': [], 'stateA': [], 'stateB': []}
    for atom in topology.atoms():
        if not hasattr(atom, 'weight'): continue
        if atom.weight == 1.0:
            ligand_info['core'].append(atom.index)
        elif atom.weight == 2.0:
            ligand_info['stateA'].append(atom.index)
        elif atom.weight == 3.0:
            ligand_info['stateB'].append(atom.index)
    return ligand_info

