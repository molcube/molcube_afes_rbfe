import openmm

def updateBarostat(system, inputs):
    if not inputs.pcouple: return

    if inputs.p_type == 'ISOTROPIC':
        barostat = openmm.MonteCarloBarostat(
                        inputs.p_ref,
                        inputs.temperature,
                        inputs.p_freq)

    elif inputs.p_type == 'MEMBRANE':
        barostat = openmm.MonteCarloMembraneBarostat(
                        inputs.p_ref,
                        inputs.p_tens,
                        inputs.temperature,
                        inputs.p_XYMode,
                        inputs.p_ZMode,
                        inputs.p_freq)

    elif inputs.p_type == 'ANISOTROPIC':
        barostat = openmm.MonteCarloAnisotropicBarostat(
                        inputs.p_ref,
                        inputs.temperature,
                        inputs.p_scale[0],
                        inputs.p_scale[1],
                        inputs.p_scale[2],
                        inputs.p_freq)

    system.addForce(barostat)

