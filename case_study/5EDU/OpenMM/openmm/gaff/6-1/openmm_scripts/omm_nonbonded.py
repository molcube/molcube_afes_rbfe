    nb14_force2.addGlobalParameter('Roff', inputs.r_off)

    for parameter in ['sigmaA', 'epsilonA', 'sigmaB', 'epsilonB']:
        nb14_force2.addPerBondParameter(parameter)

    exception_list = dict()
    for i in range(nbforce.getNumExceptionParameterOffsets()):
        param_name, exception_index, charge_scale, sigma_scale, epsilon_scale = nbforce.getExceptionParameterOffset(i)
        if param_name != 'lambda_sterics_core': continue
        atom1, atom2, charge, sigma, epsilon = nbforce.getExceptionParameters(exception_index)
        sigmaB   = sigma + sigma_scale*nanometers
        epsilonB = epsilon + epsilon_scale*kilojoules_per_mole
        exception_list[exception_index] = (sigma, epsilon, sigmaB, epsilonB)
        nbforce.setExceptionParameterOffset(i, param_name, exception_index, charge_scale, 0, 0)

