def get_vfswitch_energy_function():
    efunc = 'select(step(r-Ron),(cr12*rjunk12 - cr6*rjunk6),' \
            '(acoef/r^12-bcoef/r^6-acoef/onoff^6+bcoef/onoff^3));' \
            'cr12 = acoef*ofdif6;' \
            'cr6  = bcoef*ofdif3;' \
            'rjunk12 = (1.0/r^6-1.0/Roff6)^2;' \
            'rjunk6  = (1.0/r^3-1.0/Roff3)^2;' \
            'ofdif6 = Roff6/(Roff6 - Ron^6);' \
            'ofdif3 = Roff3/(Roff3 - Ron^3);' \
            'onoff = Ron*Roff;' \
            'Roff6 = Roff^6;' \
            'Roff3 = Roff^3;' \
            'acoef = 4.0*epsilon*sigma^12;' \
            'bcoef = 4.0*epsilon*sigma^6;'
    return efunc

def get_vfswitch_softcore_energy_function(nb_comb_rule):
    efunc = 'select(step(r-r_LJ), select(step(r-Ron),' \
            '(cr12*rjunk12 - cr6*rjunk6),' \
            '(acoef/r^12 - bcoef/r^6 - V_offset)),' \
            'U_sterics_quad);' \
            'U_sterics_quad = U_sterics_cut + Force * (((r - r_LJ)^2)/2 - (r - r_LJ));' \
            'U_sterics_cut = acoef/(r_LJ^12) - bcoef/(r_LJ^6) - V_offset;' \
            'Force = 12*acoef/(r_LJ^13) - 6*bcoef/(r_LJ^7);' \
            'r_LJ = softcore_alpha*((26/7)*(sigma^6)*lambda_sterics_deprecated)^(1/6);' \
            'V_offset = acoef/onoff^6 - bcoef/onoff^3;' \
            'onoff = Ron * Roff;' \
            'cr12 = acoef * ofdif6;' \
            'cr6  = bcoef * ofdif3;' \
            'rjunk12 = (1.0/r^6 - 1.0/Roff^6)^2;' \
            'rjunk6  = (1.0/r^3 - 1.0/Roff^3)^2;' \
            'ofdif6 = Roff^6 / (Roff^6 - Ron^6);' \
            'ofdif3 = Roff^3 / (Roff^3 - Ron^3);' \
            'acoef = 4*epsilon*sigma^12;' \
            'bcoef = 4*epsilon*sigma^6;' \
            'lambda_sterics_deprecated = stateB_interaction*(1.0 - lambda_sterics_insert) + ' \
            'stateA_interaction*lambda_sterics_delete;' \
            'epsilon = (1-lambda_sterics)*epsilonA + lambda_sterics*epsilonB;' \
            'sigma = (1-lambda_sterics)*sigmaA + lambda_sterics*sigmaB;' \
            'lambda_sterics = core_interaction*lambda_sterics_core + ' \
            'stateB_interaction*lambda_sterics_insert + ' \
            'stateA_interaction*lambda_sterics_delete;' \
            'core_interaction = delta(unique_stateA1+unique_stateA2+unique_stateB1+unique_stateB2);' \
            'stateB_interaction = max(unique_stateB1, unique_stateB2);' \
            'stateA_interaction = max(unique_stateA1, unique_stateA2);' \
            'epsilonB = sqrt(epsilonB1*epsilonB2);' \
            'epsilonA = sqrt(epsilonA1*epsilonA2);'

    if nb_comb_rule == 1:
        efunc += 'sigmaB = 0.5*(sigmaB1 + sigmaB2);'
        efunc += 'sigmaA = 0.5*(sigmaA1 + sigmaA2);'
    elif nb_comb_rule == 2:
        efunc += 'sigmaB = sqrt(sigmaB1*sigmaB2);'
        efunc += 'sigmaA = sqrt(sigmaA1*sigmaA2);'

    return efunc

def create_vfswitch_force(nbforce, ligand_info, inputs):
    efunc = get_vfswitch_energy_function()
    efunc += 'epsilon = sqrt(epsilon1*epsilon2);'
    if inputs.nb_comb_rule == 1:
        efunc += 'sigma = (sigma1+sigma2)/2.0;'
    elif inputs.nb_comb_rule == 2:
        efunc += 'sigma = sqrt(sigma1*sigma2);'

    force = CustomNonbondedForce(efunc)
    force.addGlobalParameter('Ron', inputs.r_on)
    force.addGlobalParameter('Roff', inputs.r_off)
    force.addPerParticleParameter('sigma')
    force.addPerParticleParameter('epsilon')
    force.setForceGroup(NONBONDED_FORCE_GROUP)

    ligand_atoms = set(atom for atom_list in ligand_info.values() for atom in atom_list)
    environment_atoms = list()
    for i in range(nbforce.getNumParticles()):
        charge, sigma, epsilon = nbforce.getParticleParameters(i)
        nbforce.setParticleParameters(i, charge, sigma, 0.0)
        force.addParticle([sigma, epsilon])
        if not i in ligand_atoms:
            environment_atoms.append(i)
    for i in range(nbforce.getNumExceptions()):
        atom1, atom2 = nbforce.getExceptionParameters(i)[:2]
        force.addExclusion(atom1, atom2)

    force.addInteractionGroup(environment_atoms, environment_atoms)

    return force

